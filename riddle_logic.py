def get_character_list():
    """Returns data for the sidebar, including the opening sentence."""
    return [
        {
            "name": name, 
            "image": data["image"], 
            "opening": data["opening"]
        } for name, data in CHARACTERS_DATA.items()
    ]
def get_character_details(name):
    """Returns all data for a specific character."""
    return CHARACTERS_DATA.get(name)

